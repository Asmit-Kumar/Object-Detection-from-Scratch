def run_benchmark(detector: str = 'grid'):
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    all_results = {}

    if detector == 'fcos':
        print("=" * 90)
        print("  FCOS ANCHOR-FREE RESNET DETECTOR BENCHMARK (AUTO-TUNED THRESHOLDS)")
        print(f"  Device: {device} | 10,000 Test Images across 4 Placements")
        print("=" * 90)

        for sz in SIZES:
            print(f"\nEvaluating FCOS Preset: '{sz.upper()}'...")
            pipe_tune = FCOSPipeline(size=sz, device=device, conf_threshold=0.50)
            tune_loader = get_detection_loaders(
                data_root=f"{TUNE_PATH}/random", batch_size=128, test_only=True, num_workers=0, fcos=True
            )
            opt_conf = pipe_tune.tune_threshold(tune_loader)
            print(f"  [Auto-Tuned] Optimal threshold for FCOS {sz.upper()}: conf = {opt_conf:.2f} (tuned on {TUNE_PATH}/random)")

            pipe = FCOSPipeline(size=sz, device=device, conf_threshold=opt_conf)
            pure = pipe.measure_inference(tune_loader)
            print(f"  [Pure Inference] model(images) only, batch={pure['batch_size']}: {pure['median_img_s']:.1f} img/s (median of {pure['repeats']})")
            all_results[sz] = {
                'opt_conf': opt_conf,
                'tune_data_root': f"{TUNE_PATH}/random",
                'pure_inference': pure,
                'placements': {},
                'summary': {},
            }

            total_det_p = 0.0
            total_det_r = 0.0
            total_cls_acc = 0.0
            total_e2e_f1 = 0.0
            total_fps = 0.0

            for p in PLACEMENTS:
                loader = get_detection_loaders(
                    data_root=f"{BENCHMARK_PATH}/{p}", batch_size=128, test_only=True, num_workers=0, fcos=True
                )
                res = pipe.evaluate_loader(loader)
                all_results[sz]['placements'][p] = res
                total_det_p += res['det_precision']
                total_det_r += res['det_recall']
                total_cls_acc += res['classifier_acc']
                total_e2e_f1 += res['e2e_f1']
                total_fps += res['eval_loop_fps']
                print(f"  [{p:<6}] Det P={res['det_precision']:.4f} R={res['det_recall']:.4f} | Cls Acc={res['classifier_acc']:.4f} | E2E F1={res['e2e_f1']:.4f} | Eval-loop={res['eval_loop_fps']:.1f} img/s")

            num_p = len(PLACEMENTS)
            avg_res = {
                'avg_det_precision': round(total_det_p / num_p, 4),
                'avg_det_recall': round(total_det_r / num_p, 4),
                'avg_classifier_acc': round(total_cls_acc / num_p, 4),
                'avg_e2e_f1': round(total_e2e_f1 / num_p, 4),
                'avg_eval_loop_fps': round(total_fps / num_p, 1),
                'pure_inference_img_s': pure['median_img_s'],
            }
            all_results[sz]['summary'] = avg_res
            print(
                f"  [AVERAGE {sz.upper()}] Det P={avg_res['avg_det_precision']:.4f} "
                f"R={avg_res['avg_det_recall']:.4f} | "
                f"Cls Acc={avg_res['avg_classifier_acc']:.4f} | "
                f"E2E F1={avg_res['avg_e2e_f1']:.4f} | "
                f"Eval-loop={avg_res['avg_eval_loop_fps']:.1f} img/s | "
                f"Pure inference={avg_res['pure_inference_img_s']:.1f} img/s"
            )

        print("\n" + "=" * 90)
        print("  FULL FCOS BENCHMARK SUMMARY")
        print("=" * 90)
        print(
            f"{'Size':<6} {'Conf':<6} {'Layout':<8} {'Det P':<8} {'Det R':<8} "
            f"{'Cls Acc':<10} {'E2E F1':<9} {'Loop FPS':<8}"
        )
        print("-" * 90)
        for sz, data in all_results.items():
            conf_t = data['opt_conf']
            for placement, result in data['placements'].items():
                print(
                    f"{sz.upper():<6} {conf_t:<6.2f} {placement:<8} "
                    f"{result['det_precision']:<8.4f} {result['det_recall']:<8.4f} "
                    f"{result['classifier_acc']:<10.4f} {result['e2e_f1']:<9.4f} "
                    f"{result['eval_loop_fps']:<8.1f}"
                )
            summary = data['summary']
            print(
                f"{sz.upper():<6} {conf_t:<6.2f} {'AVERAGE':<8} "
                f"{summary['avg_det_precision']:<8.4f} {summary['avg_det_recall']:<8.4f} "
                f"{summary['avg_classifier_acc']:<10.4f} {summary['avg_e2e_f1']:<9.4f} "
                f"{summary['avg_eval_loop_fps']:<8.1f}"
            )
        print("=" * 90)

        out_file = Path('benchmark/fcos_results.json')
        out_file.parent.mkdir(parents=True, exist_ok=True)
        with open(out_file, 'w') as f:
            json.dump(all_results, f, indent=2)
        print(f"\nSaved raw FCOS evaluation metrics to '{out_file}'")
        return

    print("=" * 90)
    print("  SINGLE-STAGE & MULTI-ANCHOR UNIFIED DETECTOR BENCHMARK (AUTO-TUNED THRESHOLDS)")
    print("=" * 90)

    for v in VARIANTS:
        v_name = v['name']
        prefix = v['prefix']
        v_sizes = v.get('sizes', SIZES)
        all_results[v_name] = {}

        for sz in v_sizes:
            print(f"\nEvaluating Variant '{v_name}' | Preset: '{sz.upper()}' ({SIZE_LABELS[sz]})...")
            pipe_tune = SingleStagePipeline(size=sz, prefix=prefix, conf_threshold=0.65)

            if pipe_tune.anchors_wh is None and prefix.startswith('3_'):
                print(f"  [Skipping] Checkpoint not found for {prefix}{sz}_best.pth")
                continue

            tune_loader = get_detection_loaders(
                data_root=f"{TUNE_PATH}/random", batch_size=128, test_only=True, num_workers=0,
                anchors_wh=pipe_tune.anchors_wh, num_anchors=pipe_tune.anchors_wh.shape[0],
            )
            opt_conf = pipe_tune.tune_threshold(tune_loader)
            print(f"  [Auto-Tuned] Optimal threshold for {v_name} {sz.upper()}: conf = {opt_conf:.2f} (tuned on {TUNE_PATH}/random)")

            pipe = SingleStagePipeline(size=sz, prefix=prefix, conf_threshold=opt_conf)
            pure = pipe.measure_inference(tune_loader)
            print(f"  [Pure Inference] model(images) only, batch={pure['batch_size']}: {pure['median_img_s']:.1f} img/s (median of {pure['repeats']}) | arch {pipe.architecture}")
            all_results[v_name][sz] = {
                'opt_conf': opt_conf,
                'tune_data_root': f"{TUNE_PATH}/random",
                'architecture': pipe.architecture,
                'pure_inference': pure,
                'placements': {},
            }

            for p in PLACEMENTS:
                data_dir = f"{BENCHMARK_PATH}/{p}"
                loader = get_detection_loaders(
                    data_root=data_dir, batch_size=128, test_only=True, num_workers=0,
                    anchors_wh=pipe.anchors_wh, num_anchors=pipe.anchors_wh.shape[0],
                )
                res = pipe.evaluate_loader(loader)
                # GT is read back from the encoded target grid; make sure no object was dropped by a cell collision.
                expected_gt = sum(len(r.labels) for r in loader.dataset.reader.records)
                assert res['total_gt'] == expected_gt, (v_name, sz, p, res['total_gt'], expected_gt)
                all_results[v_name][sz]['placements'][p] = res
                print(f"  [{p:<6}] Det P={res['det_precision']:.4f} R={res['det_recall']:.4f} | Cls Acc={res['classifier_acc']:.4f} | E2E F1={res['e2e_f1']:.4f} | Eval-loop={res['eval_loop_fps']:.1f} img/s")

            pl = all_results[v_name][sz]['placements']
            all_results[v_name][sz]['summary'] = {
                'avg_det_precision': round(np.mean([pl[p]['det_precision'] for p in PLACEMENTS]), 4),
                'avg_det_recall': round(np.mean([pl[p]['det_recall'] for p in PLACEMENTS]), 4),
                'avg_classifier_acc': round(np.mean([pl[p]['classifier_acc'] for p in PLACEMENTS]), 4),
                'avg_e2e_f1': round(np.mean([pl[p]['e2e_f1'] for p in PLACEMENTS]), 4),
                'avg_eval_loop_fps': round(np.mean([pl[p]['eval_loop_fps'] for p in PLACEMENTS]), 1),
                'pure_inference_img_s': pure['median_img_s'],
            }

    print("\n" + "=" * 90)
    print("  FULL BENCHMARK RESULTS")
    print("=" * 90)
    print(f"{'Variant':<18} {'Size':<6} {'Conf':<6} {'Layout':<8} {'Det P':<8} {'Det R':<8} {'Cls Acc':<10} {'E2E F1':<9} {'Loop FPS':<8}")
    print("-" * 90)

    for v_name, sizes_res in all_results.items():
        for sz, data in sizes_res.items():
            conf_t = data['opt_conf']
            for p, r in data['placements'].items():
                print(f"{v_name:<18} {sz.upper():<6} {conf_t:<6.2f} {p:<8} {r['det_precision']:<8.4f} {r['det_recall']:<8.4f} {r['classifier_acc']:<10.4f} {r['e2e_f1']:<9.4f} {r['eval_loop_fps']:<8.1f}")
    print("=" * 90)

    out_file = Path('benchmark/multi_anchor_results.json')
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, 'w') as f:
        json.dump(all_results, f, indent=2)
    print(f"\nSaved raw evaluation metrics to '{out_file}'")


